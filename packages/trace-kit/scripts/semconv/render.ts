import type { InferOutput } from 'valibot'

import { array, looseObject, object, optional, parse, string, union } from 'valibot'

const memberSchema = looseObject({
  id: string(),
  value: union([string(), looseObject({})]),
  brief: optional(string()),
  stability: optional(string()),
})

const attributeSchema = looseObject({
  key: string(),
  brief: optional(string()),
  stability: optional(string()),
  type: union([string(), looseObject({ members: array(memberSchema) })]),
})

const metricSchema = looseObject({
  name: string(),
  instrument: string(),
  unit: string(),
  brief: optional(string()),
  stability: optional(string()),
})

/** The subset of a Weaver `definition/2` file that the generator reads. */
export const registryFileSchema = looseObject({
  attributes: optional(array(attributeSchema)),
  metrics: optional(array(metricSchema)),
})

export type RegistryFile = InferOutput<typeof registryFileSchema>

const sourceSchema = object({ commit: string(), files: array(string()) })

/** Converts a dotted semantic convention name to an upper snake case identifier. */
export function constantName(name: string): string {
  return name.replace(/[^a-z0-9]+/gi, '_').toUpperCase()
}

function docComment(lines: Array<string | undefined>): string {
  const text = lines
    .filter((line): line is string => Boolean(line))
    .map(line => line.replace(/\s+/g, ' ').replace(/\*\//g, '*\\/').trim())
  return ['/**', ...text.map(line => ` * ${line}`), ' */'].join('\n')
}

function stabilityLine(stability: string | undefined): string | undefined {
  return stability ? `Stability: \`${stability}\`.` : undefined
}

/** Renders the constants module for the parsed registry files. Throws on duplicate constant names. */
export function renderModule(source: { commit: string, files: string[] }, files: RegistryFile[]): string {
  const { commit, files: paths } = parse(sourceSchema, source)
  const seen = new Set<string>()
  const blocks: string[] = []

  function add(name: string, doc: string, value: string): void {
    if (seen.has(name))
      throw new Error(`Duplicate constant ${name}`)
    seen.add(name)
    blocks.push(`${doc}\nexport const ${name} = '${value}'`)
  }

  const attributes = files.flatMap(file => file.attributes ?? []).sort((a, b) => a.key.localeCompare(b.key))
  for (const attribute of attributes) {
    add(`ATTR_${constantName(attribute.key)}`, docComment([attribute.brief, stabilityLine(attribute.stability)]), attribute.key)
    if (typeof attribute.type === 'string')
      continue
    for (const member of attribute.type.members) {
      if (typeof member.value !== 'string')
        continue
      add(`${constantName(attribute.key)}_VALUE_${constantName(member.id)}`, docComment([member.brief, stabilityLine(member.stability)]), member.value)
    }
  }

  const metrics = files.flatMap(file => file.metrics ?? []).sort((a, b) => a.name.localeCompare(b.name))
  for (const metric of metrics)
    add(`METRIC_${constantName(metric.name)}`, docComment([metric.brief, `Instrument: \`${metric.instrument}\`. Unit: \`${metric.unit}\`.`, stabilityLine(metric.stability)]), metric.name)

  return [
    '// This file is generated by `pnpm -F @proj-airi/trace-kit generate:semconv`. Do not edit it.',
    '// The comments are upstream briefs, so the comment wording rules do not apply.',
    '/* eslint-disable slop/no-jargon */',
    `// Source: https://github.com/open-telemetry/semantic-conventions-genai/tree/${commit}`,
    `// Files: ${paths.join(', ')}`,
    '',
    `/** The semantic-conventions-genai commit that these constants come from. */`,
    `export const SEMCONV_GENAI_COMMIT = '${commit}'`,
    '',
    blocks.join('\n\n'),
    '',
  ].join('\n')
}
