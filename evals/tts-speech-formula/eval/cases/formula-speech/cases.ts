import type { Language } from './languages'

/**
 * How a case is graded. Each mode compares the reference with what a listener wrote down.
 *
 * - `symbolic`: equal after normalization, or equivalent by symbolic math. `6/π²` is not `π²/6`.
 * - `norm`: equal after normalization only. Use it when two different forms must not pass.
 * - `chem`: the same species, coefficients, and arrow class.
 * - `currency`: the same dollar amounts, and the same inline math.
 */
export type GradingMode = 'symbolic' | 'norm' | 'chem' | 'currency'

/** One expected item of a currency sentence: an amount in US dollars, or an inline formula. */
export type CurrencyItem = readonly ['USD', number] | readonly ['MATH', string]

export interface FormulaSpeechCase {
  /** Stable id. Reports use it to match the same case across runs. */
  id: string
  /** The group of notation that the case covers, for example `limit` or `chem`. */
  stratum: string
  /** Where the case comes from: a Goal task, a textbook, or a dataset. */
  source: string
  mode: GradingMode
  /** Reference LaTeX, or the expected items of a currency sentence. */
  reference: string | readonly CurrencyItem[]
  /** The markdown that the methods get: one text for all languages, or one sentence per language. */
  input: string | Readonly<Record<Language, string>>
  /**
   * Overrides the letter case policy of the grader.
   *
   * @default derived from the reference: `sensitive` when it uses both cases of one letter
   */
  letterCase?: 'fold' | 'sensitive'
  note: string
}

